#!/bin/bash
# Builds DynamicDock with SwiftPM and assembles a signed .app bundle in build/.
# Usage: Scripts/build-app.sh [debug|release]   (default: release)
# Set UNIVERSAL=1 to build for both Apple silicon and Intel Macs.
set -euo pipefail

CONFIG="${1:-release}"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
APP="$ROOT/build/DynamicDock.app"
# Set SIGN_IDENTITY to a certificate name for a stable signature; "-" is ad-hoc.
SIGN_IDENTITY="${SIGN_IDENTITY:--}"

ARCH_FLAGS=()
if [[ "${UNIVERSAL:-0}" == "1" ]]; then
    ARCH_FLAGS=(--arch arm64 --arch x86_64)
fi

cd "$ROOT"
swift build -c "$CONFIG" ${ARCH_FLAGS[@]+"${ARCH_FLAGS[@]}"}
BIN_DIR="$(swift build -c "$CONFIG" ${ARCH_FLAGS[@]+"${ARCH_FLAGS[@]}"} --show-bin-path)"

rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"
cp "$BIN_DIR/DynamicDock" "$APP/Contents/MacOS/DynamicDock"
cp "$ROOT/Resources/Info.plist" "$APP/Contents/Info.plist"
# The icon is generated by Scripts/make-icon.swift and checked in.
cp "$ROOT/Resources/AppIcon.icns" "$APP/Contents/Resources/AppIcon.icns"

codesign --force --options runtime \
    --entitlements "$ROOT/Resources/DynamicDock.entitlements" \
    --sign "$SIGN_IDENTITY" "$APP"

echo "Built $APP"
